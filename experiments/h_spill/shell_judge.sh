#!/bin/bash
# Direct shell-loop judging via gemini CLI for Flash judge B.
# Reads the chain stage_*.txt files and calls gemini for missing judgments.
# Saves both .json (parsed) and .meta.json (full envelope) per cell.

cd "$(dirname "$0")"
RESULTS=results
CHAINS=$RESULTS/chains
JUDGMENTS=$RESULTS/judgments
JUDGE_ID=gemini25flash
MODEL=gemini-2.5-flash
PROMPT_PREFIX='You are evaluating whether a piece of text was generated by an AI (LLM) or written by a human. Return only a JSON object with exactly two fields: ai_probability (float between 0.0 and 1.0; 1.0 = definitely AI, 0.0 = definitely human, 0.5 = uncertain) and reasoning (1-2 sentence justification). Reply with the JSON object only, no other text.

TEXT TO EVALUATE:

'

n_done=0
n_skip=0
for chain_dir in "$CHAINS"/*/; do
  sid=$(basename "$chain_dir")
  for stage in 0 1 2 3; do
    text_file="$chain_dir/stage_${stage}.txt"
    json_file="$JUDGMENTS/${sid}_${stage}_${JUDGE_ID}.json"
    meta_file="$JUDGMENTS/${sid}_${stage}_${JUDGE_ID}.meta.json"
    [ -f "$text_file" ] || continue
    if [ -f "$json_file" ]; then
      n_skip=$((n_skip+1))
      continue
    fi
    text=$(cat "$text_file")
    echo "[$(date +%H:%M:%S)] judging $sid/s$stage/$JUDGE_ID..."
    t0=$(date +%s)
    envelope=$(gemini -m "$MODEL" -o json -p "$PROMPT_PREFIX$text" 2>/dev/null)
    t1=$(date +%s)
    wall=$((t1 - t0))
    # Extract response field
    resp=$(echo "$envelope" | python3 -c "import json,sys; d=json.loads(sys.stdin.read()); print(d.get('response',''))" 2>/dev/null)
    # Strip markdown fences and parse the inner JSON
    inner=$(echo "$resp" | sed -e '/^```/d')
    parsed=$(echo "$inner" | python3 -c "
import json, sys, re
t = sys.stdin.read()
m = re.search(r'\{[^{}]*\"ai_probability\"[^{}]*\}', t, re.DOTALL)
if m:
    try:
        d = json.loads(m.group(0))
        if 'ai_probability' in d and 0 <= float(d['ai_probability']) <= 1:
            print(json.dumps({'ai_probability': float(d['ai_probability']), 'reasoning': d.get('reasoning','')}, indent=2))
            sys.exit(0)
    except Exception:
        pass
sys.exit(1)
" 2>/dev/null)
    if [ -n "$parsed" ]; then
      echo "$parsed" > "$json_file"
      # Extract token + latency from envelope into meta
      echo "$envelope" | python3 -c "
import json, sys
d = json.loads(sys.stdin.read())
stats_m = (d.get('stats') or {}).get('models') or {}
out = {'seed_id': '$sid', 'stage': $stage, 'judge': '$JUDGE_ID', 'wall_s': $wall}
if stats_m:
    k = next(iter(stats_m))
    m = stats_m[k]
    tk = m.get('tokens') or {}
    api = m.get('api') or {}
    out['input_tokens'] = tk.get('input')
    out['output_tokens'] = tk.get('candidates')
    out['duration_ms'] = api.get('totalLatencyMs')
print(json.dumps(out, indent=2))
" > "$meta_file"
      n_done=$((n_done+1))
      ai_p=$(python3 -c "import json; print(json.load(open('$json_file'))['ai_probability'])")
      echo "  -> ai_p=$ai_p (${wall}s)  done_this_run=$n_done"
    else
      echo "  -> PARSE-FAIL (${wall}s)"
    fi
  done
done
echo "=== shell_judge done: n_done=$n_done n_skip=$n_skip ==="
