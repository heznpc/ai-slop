# ---------------- CLI invocation ----------------

def call_cli(target: dict, prompt: str) -> tuple[str, dict, float, int]:
    t0 = time.time()
    if target["uses_stdin"]:
        proc = subprocess.run(target["cmd"], input=prompt, text=True, capture_output=True, timeout=300)
    else:
        proc = subprocess.run(target["cmd"] + [prompt], text=True, capture_output=True, timeout=300)
    wall = time.time() - t0
    out = proc.stdout or ""

    metrics: dict = {
        "input_tokens": None, "output_tokens": None,
        "cache_read_tokens": None, "cache_creation_tokens": None,
        "total_cost_usd": None, "duration_ms": None, "duration_api_ms": None,
    }
    model_text = out

    try:
        env = json.loads(out)
        if target["family"] == "claude":
            model_text = env.get("result", out)
            usage = env.get("usage") or {}
            metrics["input_tokens"] = usage.get("input_tokens")
            metrics["output_tokens"] = usage.get("output_tokens")
            metrics["cache_read_tokens"] = usage.get("cache_read_input_tokens")
            metrics["cache_creation_tokens"] = usage.get("cache_creation_input_tokens")
            metrics["total_cost_usd"] = env.get("total_cost_usd")
            metrics["duration_ms"] = env.get("duration_ms")
            metrics["duration_api_ms"] = env.get("duration_api_ms")
        elif target["family"] == "gemini":
            model_text = env.get("response", out)
            stats_models = (env.get("stats") or {}).get("models") or {}
            if stats_models:
                first = next(iter(stats_models))
                m = stats_models[first]
                tokens = m.get("tokens") or {}
                api = m.get("api") or {}
                metrics["input_tokens"] = tokens.get("input")
                metrics["output_tokens"] = tokens.get("candidates")
                metrics["cache_read_tokens"] = tokens.get("cached")
                metrics["duration_ms"] = api.get("totalLatencyMs")
    except (json.JSONDecodeError, AttributeError, StopIteration):
        pass

    return model_text, metrics, wall, proc.returncode


# ---------------- Stage 1: arXiv seed acquire ----------------

def reconstruct_abstract(inverted_idx: dict) -> str:
    """OpenAlex stores abstracts as inverted index {word: [positions]}; reconstruct."""
    if not inverted_idx:
        return ""
    positions: list[tuple[int, str]] = []
    for word, pos_list in inverted_idx.items():
        for p in pos_list:
            positions.append((p, word))
    positions.sort()
    return " ".join(w for _, w in positions)


def acquire_seeds() -> list[dict]:
    seeds_path = RESULTS / "seeds.json"
    if seeds_path.exists():
        log(f"seeds.json exists, loading cached")
        return json.loads(seeds_path.read_text())
    log(f"fetching {N_SEEDS} OpenAlex abstracts (NLP|AI, {SEED_YEAR_MIN}-{SEED_YEAR_MAX})")
    # OpenAlex Works API with abstract_inverted_index
    # Filter: NLP concept (C204321447) OR AI concept (C154945302); year 2024-2026; English
    params = {
        "filter": f"concepts.id:C204321447|C154945302,publication_year:{SEED_YEAR_MIN}-{SEED_YEAR_MAX},language:en",
        "per-page": 50,
        "sort": "publication_date:desc",
        "mailto": OPENALEX_EMAIL,
        "select": "id,title,publication_year,publication_date,abstract_inverted_index",
    }
    url = "https://api.openalex.org/works?" + urllib.parse.urlencode(params)
    req = urllib.request.Request(url, headers={"User-Agent": f"ai-slop-paper-h-spill/1.0 (mailto:{OPENALEX_EMAIL})"})
    for attempt in range(3):
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                payload = json.loads(resp.read().decode("utf-8"))
            break
        except urllib.error.HTTPError as e:
            if e.code == 429:
                back = (5 ** attempt) if attempt > 0 else 5
                log(f"  429 from OpenAlex, sleeping {back}s")
                time.sleep(back)
                continue
            raise
    else:
        raise RuntimeError("OpenAlex seed fetch failed after 3 retries")

    entries = []
    for w in payload.get("results", []):
        abs_text = reconstruct_abstract(w.get("abstract_inverted_index") or {})
        if len(abs_text) < 400:  # need enough for transformation
            continue
        # Use OpenAlex Work ID (URL stem) as seed_id
        wid_full = w.get("id", "")
        wid = wid_full.rsplit("/", 1)[-1] if wid_full else None
        if not wid:
            continue
        entries.append({
            "arxiv_id": wid,  # keeping field name for downstream compatibility
            "openalex_id": wid_full,
            "title": " ".join((w.get("title") or "").split()),
            "abstract": abs_text,
            "published": w.get("publication_date"),
            "year": w.get("publication_year"),
        })
        if len(entries) >= N_SEEDS:
            break
    if len(entries) < N_SEEDS:
        raise RuntimeError(f"only {len(entries)} valid seeds from OpenAlex (wanted {N_SEEDS})")
    seeds_path.write_text(json.dumps(entries, indent=2))
    log(f"seeds.json written: {len(entries)} seeds (source: OpenAlex)")
    return entries


# ---------------- Stage 2: generation chain ----------------

def generate_chains(seeds: list[dict]) -> None:
    log(f"=== generation: {len(seeds)} chains x 3 transformations = {len(seeds) * 3} calls ===")
    cum_cost = 0.0
    cum_wall = 0.0
    n_done = 0
    n_total = len(seeds) * 3
    for seed in seeds:
        sid = seed["arxiv_id"]
        chain_dir = CHAINS / sid
        chain_dir.mkdir(exist_ok=True)
        # Stage 0: write original abstract verbatim
        s0_path = chain_dir / "stage_0.txt"
        if not s0_path.exists():
            s0_path.write_text(seed["abstract"])
        prev_text = seed["abstract"]
        for stage in STAGES[1:]:
            sp = chain_dir / f"stage_{stage['index']}.txt"
            mp = chain_dir / f"stage_{stage['index']}.meta.json"
            if sp.exists():
                prev_text = sp.read_text()
                n_done += 1
                continue
            prompt = stage["transform"] + "\n\n" + prev_text
            text, metrics, wall, rc = call_cli(GENERATOR, prompt)
            sp.write_text(text)
            mp.write_text(json.dumps({"seed_id": sid, "stage": stage["index"], "stage_name": stage["name"], "wall_s": round(wall, 2), **metrics}, indent=2))
            cum_cost += metrics.get("total_cost_usd") or 0.0
            cum_wall += wall
            n_done += 1
            cost_str = f" cost=${metrics['total_cost_usd']:.4f}" if metrics["total_cost_usd"] is not None else ""
            tok_str = f" in_tok={metrics['input_tokens']} out_tok={metrics['output_tokens']}" if metrics["input_tokens"] is not None else ""
            log(f"  gen [{n_done:3d}/{n_total}] {sid[:10]} stage_{stage['index']}_{stage['name']} ({wall:.1f}s{tok_str}{cost_str}; cum cost=${cum_cost:.2f})")
            prev_text = text
    log(f"=== generation done: cum_cost=${cum_cost:.2f} cum_wall={cum_wall:.1f}s ===")


# ---------------- Stage 3: judge chains ----------------

def parse_judgment(text: str) -> dict | None:
    text = text.strip()
    # Strip markdown fences
    text = re.sub(r"^```(?:json)?\s*", "", text, flags=re.MULTILINE)
    text = re.sub(r"```\s*$", "", text.strip(), flags=re.MULTILINE)
    # Direct parse
    candidates = []
    try:
        candidates.append(json.loads(text.strip()))
    except json.JSONDecodeError:
        pass
    # Regex fallback
    if not candidates:
        m = re.search(r"\{[^{}]*\"ai_probability\"[^{}]*\}", text, re.DOTALL)
        if m:
            try:
                candidates.append(json.loads(m.group(0)))
            except json.JSONDecodeError:
                pass
    if not candidates:
        m = re.search(r"\{.*?\"ai_probability\".*?\}", text, re.DOTALL)
        if m:
            blob = m.group(0)
            last = blob.rfind("}")
            if last >= 0:
                try:
                    candidates.append(json.loads(blob[: last + 1]))
                except json.JSONDecodeError:
                    pass
    for c in candidates:
        if "ai_probability" in c:
            try:
                p = float(c["ai_probability"])
                if 0.0 <= p <= 1.0:
                    return {"ai_probability": p, "reasoning": c.get("reasoning", "")}
            except (TypeError, ValueError):
                pass
    return None


def _do_single_judge(args):
    judge, sid, stage, text, label = args
    jp = JUDGMENTS / f"{sid}_{stage['index']}_{judge['id']}.json"
    mp = JUDGMENTS / f"{sid}_{stage['index']}_{judge['id']}.meta.json"
    prompt = JUDGE_PROMPT + text
    parsed = None
    out_text, metrics, wall, rc = None, None, 0.0, 0
    for attempt in range(2):
        out_text, metrics, wall, rc = call_cli(judge, prompt)
        parsed = parse_judgment(out_text)
        if parsed is not None:
            break
        prompt = JUDGE_PROMPT + text + "\n\nREMINDER: Reply with valid JSON only. No prose. No markdown."
    if parsed is None:
        return {"ok": False, "label": label, "judge_id": judge["id"], "wall_s": wall}
    jp.write_text(json.dumps(parsed, indent=2))
    mp.write_text(json.dumps({
        "seed_id": sid, "stage": stage["index"], "stage_name": stage["name"], "judge": judge["id"],
        "wall_s": round(wall, 2), **metrics,
    }, indent=2))
    return {"ok": True, "label": label, "judge_id": judge["id"], "wall_s": wall, "ai_p": parsed["ai_probability"], "cost": metrics.get("total_cost_usd") or 0.0}


def judge_chains(seeds: list[dict]) -> None:
    """Concurrent variant: per-judge concurrency lane.

    Each judge gets its own thread-pool because CLIs are expensive
    to spin up and rate-limit independently. Within a judge, we run
    `max_workers=4` so the bash window survives long enough to make
    meaningful progress before the harness kills us.
    """
    from concurrent.futures import ThreadPoolExecutor, as_completed

    log(f"=== judging: {len(seeds)} chains x 4 stages x {len(JUDGES)} judges = {len(seeds) * 4 * len(JUDGES)} calls ===")
    # Pre-compute the work list per judge
    work_per_judge: dict[str, list[tuple]] = {j["id"]: [] for j in JUDGES}
    for seed in seeds:
        sid = seed["arxiv_id"]
        for stage in STAGES:
            text_path = CHAINS / sid / f"stage_{stage['index']}.txt"
            if not text_path.exists():
                continue
            text = text_path.read_text()
            for judge in JUDGES:
                jp = JUDGMENTS / f"{sid}_{stage['index']}_{judge['id']}.json"
                if jp.exists():
                    continue
                label = f"{sid[:10]}/s{stage['index']}/{judge['id']}"
                work_per_judge[judge["id"]].append((judge, sid, stage, text, label))

    cum_cost = 0.0
    failures = 0
    n_done = 0
    n_total_remaining = sum(len(v) for v in work_per_judge.values())
    log(f"  remaining (after cache): {n_total_remaining} calls")

    # Process each judge's work pool with concurrency
    for judge in JUDGES:
        work = work_per_judge[judge["id"]]
        if not work:
            log(f"  {judge['label']}: 0 calls (all cached)")
            continue
        log(f"  {judge['label']}: {len(work)} calls (concurrency=4)")
        with ThreadPoolExecutor(max_workers=4) as ex:
            futures = {ex.submit(_do_single_judge, w): w for w in work}
            for fut in as_completed(futures):
                res = fut.result()
                n_done += 1
                if not res["ok"]:
                    failures += 1
                    log(f"  judge [{n_done:3d}/{n_total_remaining}] {res['label']} PARSE-FAIL ({res['wall_s']:.1f}s)")
                    continue
                cum_cost += res["cost"]
                log(f"  judge [{n_done:3d}/{n_total_remaining}] {res['label']} ai_p={res['ai_p']:.2f} ({res['wall_s']:.1f}s cost=${res['cost']:.4f}; cum=${cum_cost:.2f})")
    log(f"=== judging done: cum_cost=${cum_cost:.2f}  failures={failures} ===")


# ---------------- Stage 4: stylometric ----------------

SENT_END = re.compile(r"[.!?]+\s+|[.!?]+$")
WORD = re.compile(r"\b\w+\b")


def stylo_one(text: str) -> dict:
    sentences = [s.strip() for s in SENT_END.split(text) if s.strip()]
    sent_lens = [len(WORD.findall(s)) for s in sentences if WORD.findall(s)]
    words = WORD.findall(text.lower())
    if not words or not sent_lens:
        return {"mean_sent_len": float("nan"), "var_sent_len": float("nan"), "ttr": float("nan"), "word_count": 0, "char_count": len(text)}
    return {
        "mean_sent_len": float(statistics.mean(sent_lens)),
        "var_sent_len": float(statistics.pvariance(sent_lens)) if len(sent_lens) >= 2 else 0.0,
        "ttr": len(set(words)) / len(words),
        "word_count": len(words),
        "char_count": len(text),
    }


def compute_stylo(seeds: list[dict]) -> None:
    log(f"=== stylometric stats ===")
    rows = []
    for seed in seeds:
        sid = seed["arxiv_id"]
        for stage in STAGES:
            tp = CHAINS / sid / f"stage_{stage['index']}.txt"
            if not tp.exists():
                continue
            s = stylo_one(tp.read_text())
            rows.append({"seed_id": sid, "stage": stage["index"], "stage_name": stage["name"], **s})
    header = ["seed_id", "stage", "stage_name", "mean_sent_len", "var_sent_len", "ttr", "word_count", "char_count"]
    with (RESULTS / "stylo.csv").open("w") as f:
        f.write(",".join(header) + "\n")
        for r in rows:
            f.write(",".join(str(r.get(k, "")) for k in header) + "\n")
    log(f"stylo.csv written: {len(rows)} rows")


# ---------------- Stage 5: analyze ----------------

def analyze(seeds: list[dict]) -> None:
    log(f"=== analysis ===")
    # Aggregate judgments
    judgments_rows = []
    for seed in seeds:
        sid = seed["arxiv_id"]
        for stage in STAGES:
            for judge in JUDGES:
                jp = JUDGMENTS / f"{sid}_{stage['index']}_{judge['id']}.json"
                if not jp.exists():
                    continue
                p = json.loads(jp.read_text())["ai_probability"]
                judgments_rows.append({"seed_id": sid, "stage": stage["index"], "judge": judge["id"], "ai_probability": p})
    with (RESULTS / "judgments_raw.csv").open("w") as f:
        f.write("seed_id,stage,judge,ai_probability\n")
        for r in judgments_rows:
            f.write(f"{r['seed_id']},{r['stage']},{r['judge']},{r['ai_probability']}\n")

    # Per-cell panel mean
    by_cell: dict[tuple[str, int], list[float]] = {}
    for r in judgments_rows:
        by_cell.setdefault((r["seed_id"], r["stage"]), []).append(r["ai_probability"])
    panel = []
    for (sid, stg), probs in by_cell.items():
        panel.append({"seed_id": sid, "stage": stg, "n_judges": len(probs), "ai_p_mean": float(np.mean(probs)), "ai_p_min": float(min(probs)), "ai_p_max": float(max(probs))})
    with (RESULTS / "panel_per_cell.csv").open("w") as f:
        f.write("seed_id,stage,n_judges,ai_p_mean,ai_p_min,ai_p_max\n")
        for r in panel:
            f.write(f"{r['seed_id']},{r['stage']},{r['n_judges']},{r['ai_p_mean']:.4f},{r['ai_p_min']:.4f},{r['ai_p_max']:.4f}\n")

    # Per-stage mean across all 20 chains
    stage_groups: dict[int, list[float]] = {0: [], 1: [], 2: [], 3: []}
    for r in panel:
        stage_groups[r["stage"]].append(r["ai_p_mean"])
    stage_means = {s: float(np.mean(v)) for s, v in stage_groups.items() if v}
    stage_stds = {s: float(np.std(v, ddof=1)) for s, v in stage_groups.items() if len(v) > 1}
    log(f"  stage means (panel ai_probability): {stage_means}")

    # Per-chain Spearman of stage vs ai_p_mean
    chain_rhos = []
    chain_to_stage_p: dict[str, dict[int, float]] = {}
    for r in panel:
        chain_to_stage_p.setdefault(r["seed_id"], {})[r["stage"]] = r["ai_p_mean"]
    for sid, sp in chain_to_stage_p.items():
        if len(sp) < 3:
            continue
        stages_sorted = sorted(sp.keys())
        x = np.array(stages_sorted, dtype=float)
        y = np.array([sp[s] for s in stages_sorted], dtype=float)
        if len(set(y.tolist())) < 2:
            continue
        rho, _ = spearmanr(x, y)
        if not np.isnan(rho):
            chain_rhos.append(rho)
    mean_rho = float(np.mean(chain_rhos)) if chain_rhos else float("nan")

    # Permutation test for mean_rho < 0
    rng = np.random.default_rng(SEED)
    null_mean_rhos = []
    chain_pairs = []
    for sid, sp in chain_to_stage_p.items():
        if len(sp) >= 3:
            stages_sorted = sorted(sp.keys())
            chain_pairs.append((np.array(stages_sorted, dtype=float), np.array([sp[s] for s in stages_sorted], dtype=float)))
    for _ in range(PERMUTE_N):
        permuted_rhos = []
        for x, y in chain_pairs:
            y_perm = rng.permutation(y)
            if len(set(y_perm.tolist())) < 2:
                continue
            rho_p, _ = spearmanr(x, y_perm)
            if not np.isnan(rho_p):
                permuted_rhos.append(rho_p)
        if permuted_rhos:
            null_mean_rhos.append(np.mean(permuted_rhos))
    p_one_sided = float(np.mean([n <= mean_rho for n in null_mean_rhos])) if null_mean_rhos else float("nan")
    log(f"  mean per-chain Spearman rho = {mean_rho:.4f}  perm p (one-sided less) = {p_one_sided:.4f}")

    # Mann-Kendall on 4-stage means
    def mann_kendall(seq):
        n = len(seq)
        s = 0
        for i in range(n - 1):
            for j in range(i + 1, n):
                s += np.sign(seq[j] - seq[i])
        return int(s)
    means_seq = [stage_means[s] for s in sorted(stage_means.keys())]
    mk_s = mann_kendall(means_seq)
    log(f"  Mann-Kendall S on 4-stage means = {mk_s} (monotonic decreasing if S < 0)")

    # Bootstrap CI per stage
    ci_per_stage = {}
    for s in sorted(stage_groups.keys()):
        vals = np.array(stage_groups[s])
        if len(vals) < 3:
            ci_per_stage[s] = (float("nan"), float("nan"))
            continue
        bs = []
        for _ in range(BOOTSTRAP_N):
            idx = rng.integers(0, len(vals), size=len(vals))
            bs.append(float(np.mean(vals[idx])))
        ci_per_stage[s] = (float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5)))

    # Stylometric per-stage means
    stylo_stage_means = {}
    if (RESULTS / "stylo.csv").exists():
        import csv
        with (RESULTS / "stylo.csv").open() as f:
            reader = csv.DictReader(f)
            stylo_by_stage: dict[int, list[dict]] = {}
            for r in reader:
                try:
                    stage = int(r["stage"])
                except ValueError:
                    continue
                stylo_by_stage.setdefault(stage, []).append(r)
        for stage, rs in stylo_by_stage.items():
            stylo_stage_means[stage] = {
                "mean_sent_len": float(np.mean([float(x["mean_sent_len"]) for x in rs if x["mean_sent_len"] and x["mean_sent_len"] != "nan"])),
                "var_sent_len": float(np.mean([float(x["var_sent_len"]) for x in rs if x["var_sent_len"] and x["var_sent_len"] != "nan"])),
                "ttr": float(np.mean([float(x["ttr"]) for x in rs if x["ttr"] and x["ttr"] != "nan"])),
                "word_count_mean": float(np.mean([int(x["word_count"]) for x in rs])),
            }

    falsified = (mean_rho >= 0) or (p_one_sided >= 0.05)
    out = {
        "n_chains": len(chain_to_stage_p),
        "n_judges": len(JUDGES),
        "stages": [s["name"] for s in STAGES],
        "stage_mean_ai_probability": stage_means,
        "stage_std_ai_probability": stage_stds,
        "stage_bootstrap_ci_95": {s: list(c) for s, c in ci_per_stage.items()},
        "per_chain_spearman_rho_mean": mean_rho,
        "per_chain_spearman_rho_n_chains_valid": len(chain_rhos),
        "permutation_p_one_sided_less": p_one_sided,
        "permutation_n": PERMUTE_N,
        "mann_kendall_S": mk_s,
        "bootstrap_n": BOOTSTRAP_N,
        "bootstrap_seed": SEED,
        "alpha": 0.05,
        "decision": "H-Spill not supported at alpha=0.05" if falsified else "consistent with H-Spill at alpha=0.05",
        "falsified": bool(falsified),
        "delta_stage0_to_stage3_ai_p_mean": (stage_means.get(3, float("nan")) - stage_means.get(0, float("nan"))) if 0 in stage_means and 3 in stage_means else None,
        "stylo_stage_means": stylo_stage_means,
    }
    (RESULTS / "h_spill_stats.json").write_text(json.dumps(out, indent=2))
    log(f"h_spill_stats.json written: decision = {out['decision']}")


