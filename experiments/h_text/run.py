RESULTS = HERE / "results"
VARIANTS = RESULTS / "variants"
JUDGMENTS = RESULTS / "judgments"
RESULTS.mkdir(exist_ok=True)
VARIANTS.mkdir(exist_ok=True)
JUDGMENTS.mkdir(exist_ok=True)

HSPILL = HERE.parent / "h_spill"
HSPILL_CHAINS = HSPILL / "results" / "chains"
HSPILL_JUDGMENTS = HSPILL / "results" / "judgments"

N_CHAINS = 15
SEED = 20260521
BOOTSTRAP_N = 10000
USEFUL_THRESHOLD = 0.70

GENERATOR = {
    "id": "sonnet46",
    "label": "Claude Sonnet 4.6",
    "cmd": ["claude", "--print", "--no-session-persistence", "--output-format", "json",
            "--model", "sonnet", "--max-budget-usd", "5"],
    "uses_stdin": True,
    "family": "claude",
}

JUDGES = [
    {
        "id": "opus47",
        "label": "Claude Opus 4.7",
        "cmd": ["claude", "--print", "--no-session-persistence", "--output-format", "json",
                "--model", "claude-opus-4-7", "--max-budget-usd", "5"],
        "uses_stdin": True,
        "family": "claude",
    },
    {
        "id": "gemini25flash",
        "label": "Gemini 2.5 Flash",
        "cmd": ["gemini", "-m", "gemini-2.5-flash", "-o", "json", "-p"],
        "uses_stdin": False,
        "family": "gemini",
    },
]

VARIANTS_SPEC = [
    {"id": "A", "label": "paraphrase", "transform":
        "Rewrite the following text. Preserve every factual claim and the overall logical structure, "
        "but change the wording, sentence rhythm, and clause-level structure. Aim for a noticeable but "
        "content-equivalent stylistic shift. Do not add disclaimers or note that this is a rewrite. "
        "Reply with only the rewritten text body."},
    {"id": "B", "label": "colloquial",  "transform":
        "Rewrite the following text in a casual, conversational register, as if a slightly opinionated "
        "human writer were summarizing it for a friend. Use contractions, hedges (\"I think\", \"sort of\"), "
        "one or two intentional digressions, and occasional em-dashes. Preserve the factual claims but "
        "make the prose feel humanly idiosyncratic. Do not add disclaimers. Reply with only the rewritten text body."},
]

JUDGE_PROMPT = (
    "You are evaluating whether a piece of text was generated by an AI (LLM) or "
    "written by a human. Return only a JSON object with exactly two fields: "
    "ai_probability (float between 0.0 and 1.0; 1.0 = definitely AI, 0.0 = definitely human, "
    "0.5 = uncertain) and reasoning (1-2 sentence justification). Reply with the JSON object only, "
    "no other text.\n\nTEXT TO EVALUATE:\n\n"
)


# ---------------- logging ----------------

LOG_LINES: list[str] = []
def log(msg: str) -> None:
    ts = datetime.now(timezone.utc).strftime("%H:%M:%S")
    line = f"[{ts}] {msg}"
    print(line, flush=True)
    LOG_LINES.append(line)


# ---------------- CLI invocation (copied from H-Spill, native usage capture) ----------------

def call_cli(target: dict, prompt: str) -> tuple[str, dict, float, int]:
    t0 = time.time()
    if target["uses_stdin"]:
        proc = subprocess.run(target["cmd"], input=prompt, text=True, capture_output=True, timeout=300)
    else:
        proc = subprocess.run(target["cmd"] + [prompt], text=True, capture_output=True, timeout=300)
    wall = time.time() - t0
    out = proc.stdout or ""

    metrics: dict = {
        "input_tokens": None, "output_tokens": None,
        "cache_read_tokens": None, "cache_creation_tokens": None,
        "total_cost_usd": None, "duration_ms": None, "duration_api_ms": None,
    }
    model_text = out

    try:
        env = json.loads(out)
        if target["family"] == "claude":
            model_text = env.get("result", out)
            usage = env.get("usage") or {}
            metrics["input_tokens"] = usage.get("input_tokens")
            metrics["output_tokens"] = usage.get("output_tokens")
            metrics["cache_read_tokens"] = usage.get("cache_read_input_tokens")
            metrics["cache_creation_tokens"] = usage.get("cache_creation_input_tokens")
            metrics["total_cost_usd"] = env.get("total_cost_usd")
            metrics["duration_ms"] = env.get("duration_ms")
            metrics["duration_api_ms"] = env.get("duration_api_ms")
        elif target["family"] == "gemini":
            model_text = env.get("response", out)
            stats_models = (env.get("stats") or {}).get("models") or {}
            if stats_models:
                first = next(iter(stats_models))
                m = stats_models[first]
                tokens = m.get("tokens") or {}
                api = m.get("api") or {}
                metrics["input_tokens"] = tokens.get("input")
                metrics["output_tokens"] = tokens.get("candidates")
                metrics["cache_read_tokens"] = tokens.get("cached")
                metrics["duration_ms"] = api.get("totalLatencyMs")
    except (json.JSONDecodeError, AttributeError, StopIteration):
        pass

    return model_text, metrics, wall, proc.returncode


# ---------------- Stage 1: load baselines ----------------

def load_baselines() -> list[dict]:
    """Pick first N_CHAINS H-Spill chains (sorted by Work ID) that have stage_1 + both H-Spill judgments."""
    if not HSPILL_CHAINS.exists():
        raise RuntimeError(f"H-Spill chains directory missing: {HSPILL_CHAINS}")
    out = []
    for chain_dir in sorted(HSPILL_CHAINS.iterdir()):
        if not chain_dir.is_dir():
            continue
        sid = chain_dir.name
        s1 = chain_dir / "stage_1.txt"
        if not s1.exists():
            continue
        # Need cached H-Spill judgments for stage_1
        op = HSPILL_JUDGMENTS / f"{sid}_1_opus47.json"
        gm = HSPILL_JUDGMENTS / f"{sid}_1_gemini25flash.json"
        if not (op.exists() and gm.exists()):
            continue
        opus_p = json.loads(op.read_text())["ai_probability"]
        gem_p = json.loads(gm.read_text())["ai_probability"]
        baseline_panel = (opus_p + gem_p) / 2
        out.append({
            "seed_id": sid,
            "stage1_text": s1.read_text(),
            "baseline_opus_ai_p": opus_p,
            "baseline_gemini25flash_ai_p": gem_p,
            "baseline_panel_ai_p": baseline_panel,
        })
        if len(out) >= N_CHAINS:
            break
    if len(out) < N_CHAINS:
        raise RuntimeError(f"only {len(out)} usable chains (need {N_CHAINS})")
    log(f"loaded {len(out)} baselines from H-Spill stage 1")
    return out


# ---------------- Stage 2: generate adversarial variants ----------------

def generate_variants(baselines: list[dict]) -> None:
    log(f"=== generation: {len(baselines)} baselines x {len(VARIANTS_SPEC)} variants = {len(baselines) * len(VARIANTS_SPEC)} calls ===")
    n_done = 0
    n_total = len(baselines) * len(VARIANTS_SPEC)
    cum_cost = 0.0
    for b in baselines:
        sid = b["seed_id"]
        for v in VARIANTS_SPEC:
            vp = VARIANTS / f"{sid}_{v['id']}.txt"
            mp = VARIANTS / f"{sid}_{v['id']}.meta.json"
            if vp.exists():
                n_done += 1
                continue
            prompt = v["transform"] + "\n\n" + b["stage1_text"]
            text, metrics, wall, rc = call_cli(GENERATOR, prompt)
            vp.write_text(text)
            mp.write_text(json.dumps({"seed_id": sid, "variant": v["id"], "label": v["label"],
                                      "wall_s": round(wall, 2), **metrics}, indent=2))
            cum_cost += metrics.get("total_cost_usd") or 0.0
            n_done += 1
            cost_str = f" cost=${metrics['total_cost_usd']:.4f}" if metrics["total_cost_usd"] is not None else ""
            tok_str = f" in={metrics['input_tokens']} out={metrics['output_tokens']}" if metrics["input_tokens"] is not None else ""
            log(f"  var [{n_done:2d}/{n_total}] {sid[:10]} variant_{v['id']}_{v['label']} ({wall:.1f}s{tok_str}{cost_str}; cum=${cum_cost:.2f})")
    log(f"=== generation done: cum=${cum_cost:.2f} ===")


# ---------------- Stage 3: judge variants ----------------

def parse_judgment(text: str) -> dict | None:
    text = text.strip()
    text = re.sub(r"^```(?:json)?\s*", "", text, flags=re.MULTILINE)
    text = re.sub(r"```\s*$", "", text.strip(), flags=re.MULTILINE)
    candidates = []
    try:
        candidates.append(json.loads(text.strip()))
    except json.JSONDecodeError:
        pass
    if not candidates:
        m = re.search(r"\{[^{}]*\"ai_probability\"[^{}]*\}", text, re.DOTALL)
        if m:
            try:
                candidates.append(json.loads(m.group(0)))
            except json.JSONDecodeError:
                pass
    if not candidates:
        m = re.search(r"\{.*?\"ai_probability\".*?\}", text, re.DOTALL)
        if m:
            blob = m.group(0)
            last = blob.rfind("}")
            if last >= 0:
                try:
                    candidates.append(json.loads(blob[: last + 1]))
                except json.JSONDecodeError:
                    pass
    for c in candidates:
        if "ai_probability" in c:
            try:
                p = float(c["ai_probability"])
                if 0.0 <= p <= 1.0:
                    return {"ai_probability": p, "reasoning": c.get("reasoning", "")}
            except (TypeError, ValueError):
                pass
    return None


def _do_one_judge(args):
    judge, sid, variant_id, text, label = args
    jp = JUDGMENTS / f"{sid}_{variant_id}_{judge['id']}.json"
    mp = JUDGMENTS / f"{sid}_{variant_id}_{judge['id']}.meta.json"
    prompt = JUDGE_PROMPT + text
    parsed = None
    out_text, metrics, wall, rc = None, None, 0.0, 0
    for attempt in range(2):
        out_text, metrics, wall, rc = call_cli(judge, prompt)
        parsed = parse_judgment(out_text)
        if parsed is not None:
            break
        prompt = JUDGE_PROMPT + text + "\n\nREMINDER: Reply with valid JSON only. No prose. No markdown."
    if parsed is None:
        return {"ok": False, "label": label, "wall_s": wall}
    jp.write_text(json.dumps(parsed, indent=2))
    mp.write_text(json.dumps({
        "seed_id": sid, "variant": variant_id, "judge": judge["id"],
        "wall_s": round(wall, 2), **metrics,
    }, indent=2))
    return {"ok": True, "label": label, "wall_s": wall, "ai_p": parsed["ai_probability"],
            "cost": metrics.get("total_cost_usd") or 0.0}


def judge_variants(baselines: list[dict]) -> None:
    log(f"=== judging variants: {len(baselines)} chains x {len(VARIANTS_SPEC)} variants x {len(JUDGES)} judges = {len(baselines) * len(VARIANTS_SPEC) * len(JUDGES)} calls ===")

    work_per_judge: dict[str, list[tuple]] = {j["id"]: [] for j in JUDGES}
    for b in baselines:
        sid = b["seed_id"]
        for v in VARIANTS_SPEC:
            vp = VARIANTS / f"{sid}_{v['id']}.txt"
            if not vp.exists():
                continue
            text = vp.read_text()
            for judge in JUDGES:
                jp = JUDGMENTS / f"{sid}_{v['id']}_{judge['id']}.json"
                if jp.exists():
                    continue
                label = f"{sid[:10]}/{v['id']}/{judge['id']}"
                work_per_judge[judge["id"]].append((judge, sid, v["id"], text, label))

    n_total_remaining = sum(len(v) for v in work_per_judge.values())
    log(f"  remaining (after cache): {n_total_remaining}")

    n_done = 0
    cum_cost = 0.0
    failures = 0
    for judge in JUDGES:
        work = work_per_judge[judge["id"]]
        if not work:
            log(f"  {judge['label']}: 0 calls (all cached)")
            continue
        log(f"  {judge['label']}: {len(work)} calls (concurrency=4)")
        with ThreadPoolExecutor(max_workers=4) as ex:
            futures = {ex.submit(_do_one_judge, w): w for w in work}
            for fut in as_completed(futures):
                res = fut.result()
                n_done += 1
                if not res["ok"]:
                    failures += 1
                    log(f"  judge [{n_done:3d}/{n_total_remaining}] {res['label']} PARSE-FAIL ({res['wall_s']:.1f}s)")
                    continue
                cum_cost += res["cost"]
                log(f"  judge [{n_done:3d}/{n_total_remaining}] {res['label']} ai_p={res['ai_p']:.2f} ({res['wall_s']:.1f}s cost=${res['cost']:.4f}; cum=${cum_cost:.2f})")
    log(f"=== judging done: cum=${cum_cost:.2f} failures={failures} ===")


# ---------------- Stage 4: analyze ----------------

SENT_END = re.compile(r"[.!?]+\s+|[.!?]+$")
WORD = re.compile(r"\b\w+\b")


def stylo_one(text: str) -> dict:
    sentences = [s.strip() for s in SENT_END.split(text) if s.strip()]
    sent_lens = [len(WORD.findall(s)) for s in sentences if WORD.findall(s)]
    words = WORD.findall(text.lower())
    if not words or not sent_lens:
        return {"mean_sent_len": float("nan"), "var_sent_len": float("nan"), "ttr": float("nan"), "word_count": 0}
    return {
        "mean_sent_len": float(statistics.mean(sent_lens)),
        "var_sent_len": float(statistics.pvariance(sent_lens)) if len(sent_lens) >= 2 else 0.0,
        "ttr": len(set(words)) / len(words),
        "word_count": len(words),
    }


def analyze(baselines: list[dict]) -> None:
    log(f"=== analysis ===")
    # Build per-chain panel scores: baseline, variant A, variant B
    per_chain = []
    for b in baselines:
        sid = b["seed_id"]
        row = {"seed_id": sid, "baseline_panel_ai_p": b["baseline_panel_ai_p"]}
        for v in VARIANTS_SPEC:
            opus_p = JUDGMENTS / f"{sid}_{v['id']}_opus47.json"
            gem_p = JUDGMENTS / f"{sid}_{v['id']}_gemini25flash.json"
            if not (opus_p.exists() and gem_p.exists()):
                row[f"variant_{v['id']}_panel_ai_p"] = None
                continue
            op = json.loads(opus_p.read_text())["ai_probability"]
            gp = json.loads(gem_p.read_text())["ai_probability"]
            row[f"variant_{v['id']}_panel_ai_p"] = (op + gp) / 2
            row[f"variant_{v['id']}_opus_ai_p"] = op
            row[f"variant_{v['id']}_gemini25flash_ai_p"] = gp
        # Mean across variants (only if both variants have data)
        vA = row.get("variant_A_panel_ai_p")
        vB = row.get("variant_B_panel_ai_p")
        if vA is not None and vB is not None:
            row["mean_variant_panel_ai_p"] = (vA + vB) / 2
        per_chain.append(row)

    # Write per-chain CSV
    header = ["seed_id", "baseline_panel_ai_p",
              "variant_A_panel_ai_p", "variant_A_opus_ai_p", "variant_A_gemini25flash_ai_p",
              "variant_B_panel_ai_p", "variant_B_opus_ai_p", "variant_B_gemini25flash_ai_p",
              "mean_variant_panel_ai_p"]
    with (RESULTS / "per_chain.csv").open("w") as f:
        f.write(",".join(header) + "\n")
        for r in per_chain:
            f.write(",".join("" if r.get(k) is None else f"{r.get(k):.4f}" if isinstance(r.get(k), float) else str(r.get(k)) for k in header) + "\n")

    # Threshold test: mean across all (chain, variant) cells of variant panel ai_p
    all_variant_ai_p = []
    for r in per_chain:
        for v in VARIANTS_SPEC:
            x = r.get(f"variant_{v['id']}_panel_ai_p")
            if x is not None:
                all_variant_ai_p.append(x)
    mean_all_variants = float(np.mean(all_variant_ai_p)) if all_variant_ai_p else float("nan")
    # Bootstrap CI
    rng = np.random.default_rng(SEED)
    bs = []
    a = np.array(all_variant_ai_p)
    for _ in range(BOOTSTRAP_N):
        idx = rng.integers(0, len(a), size=len(a))
        bs.append(float(np.mean(a[idx])))
    ci_lo, ci_hi = float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))

    # Paired Wilcoxon: baseline vs mean_variant per chain
    paired_b = [r["baseline_panel_ai_p"] for r in per_chain if r.get("mean_variant_panel_ai_p") is not None]
    paired_v = [r["mean_variant_panel_ai_p"] for r in per_chain if r.get("mean_variant_panel_ai_p") is not None]
    wilcoxon_stat = None
    wilcoxon_p = None
    if len(paired_b) >= 5:
        try:
            wstat, wp = wilcoxon(paired_b, paired_v, alternative="greater")  # H1: baseline > variant
            wilcoxon_stat = float(wstat)
            wilcoxon_p = float(wp)
        except ValueError as e:
            log(f"  wilcoxon error: {e}")

    # Per-variant breakdown (descriptive)
    per_variant = {}
    for v in VARIANTS_SPEC:
        vals = [r.get(f"variant_{v['id']}_panel_ai_p") for r in per_chain if r.get(f"variant_{v['id']}_panel_ai_p") is not None]
        bvals = [r["baseline_panel_ai_p"] for r in per_chain if r.get(f"variant_{v['id']}_panel_ai_p") is not None]
        if len(vals) >= 5:
            try:
                wstat_v, wp_v = wilcoxon(bvals, vals, alternative="greater")
            except ValueError:
                wstat_v, wp_v = None, None
            per_variant[v["id"]] = {
                "label": v["label"],
                "n": len(vals),
                "mean_panel_ai_p": float(np.mean(vals)),
                "std_panel_ai_p": float(np.std(vals, ddof=1)) if len(vals) > 1 else 0.0,
                "mean_baseline_paired": float(np.mean(bvals)),
                "delta_baseline_minus_variant": float(np.mean(bvals) - np.mean(vals)),
                "wilcoxon_stat": float(wstat_v) if wstat_v is not None else None,
                "wilcoxon_p_one_sided_greater": float(wp_v) if wp_v is not None else None,
            }

    # Stylometric on variants
    stylo_per_chain = []
    for b in baselines:
        sid = b["seed_id"]
        s_base = stylo_one(b["stage1_text"])
        s_base["seed_id"] = sid
        s_base["condition"] = "baseline"
        stylo_per_chain.append(s_base)
        for v in VARIANTS_SPEC:
            vp = VARIANTS / f"{sid}_{v['id']}.txt"
            if vp.exists():
                s = stylo_one(vp.read_text())
                s["seed_id"] = sid
                s["condition"] = f"variant_{v['id']}"
                stylo_per_chain.append(s)
    with (RESULTS / "stylo.csv").open("w") as f:
        f.write("seed_id,condition,mean_sent_len,var_sent_len,ttr,word_count\n")
        for s in stylo_per_chain:
            f.write(f"{s['seed_id']},{s['condition']},{s['mean_sent_len']:.3f},{s['var_sent_len']:.3f},{s['ttr']:.4f},{s['word_count']}\n")

    # Decision rule (both must hold for support)
    threshold_supports = bool(mean_all_variants < USEFUL_THRESHOLD)
    wilcoxon_supports = bool(wilcoxon_p is not None and wilcoxon_p < 0.05)
    h_text_supported = threshold_supports and wilcoxon_supports
    decision = "supported (threshold AND paired test both pass at alpha=0.05)" if h_text_supported else (
        "not supported -- threshold test passes but paired test fails" if threshold_supports else (
        "not supported -- paired test passes but threshold test fails" if wilcoxon_supports else
        "not supported -- both threshold and paired tests fail"))

    out = {
        "n_chains_with_both_variants": len(paired_b),
        "n_variant_cells": len(all_variant_ai_p),
        "useful_threshold": USEFUL_THRESHOLD,
        "mean_variant_panel_ai_p_all_cells": mean_all_variants,
        "bootstrap_ci_95_mean_variant": [ci_lo, ci_hi],
        "bootstrap_n": BOOTSTRAP_N,
        "bootstrap_seed": SEED,
        "threshold_test_supports_h_text_adv": threshold_supports,
        "mean_baseline_panel_ai_p": float(np.mean([r["baseline_panel_ai_p"] for r in per_chain])),
        "wilcoxon_paired_baseline_vs_mean_variant": {
            "n": len(paired_b),
            "stat": wilcoxon_stat,
            "p_one_sided_greater": wilcoxon_p,
            "alternative": "baseline > mean_variant",
            "alpha": 0.05,
            "supports_h_text_adv": wilcoxon_supports,
        },
        "per_variant_breakdown": per_variant,
        "decision": decision,
        "h_text_supported": h_text_supported,
    }
    (RESULTS / "h_text_stats.json").write_text(json.dumps(out, indent=2))
    log(f"  mean variant ai_p = {mean_all_variants:.4f}  threshold {USEFUL_THRESHOLD}  passes={threshold_supports}")
    log(f"  wilcoxon p (one-sided greater) = {wilcoxon_p}  passes={wilcoxon_supports}")
    log(f"  decision: {decision}")


# ---------------- main ----------------

def main() -> int:
    started_at = datetime.now(timezone.utc).isoformat()
    log(f"H-Text runner start. snapshot={started_at}")
    log(f"generator: {GENERATOR['label']}")
    log(f"judges: {[j['label'] for j in JUDGES]}")

    baselines = load_baselines()
    generate_variants(baselines)
    judge_variants(baselines)
    analyze(baselines)

    meta = {
        "started_at_utc": started_at,
        "finished_at_utc": datetime.now(timezone.utc).isoformat(),
        "generator": {"id": GENERATOR["id"], "label": GENERATOR["label"]},
        "judges": [{"id": j["id"], "label": j["label"]} for j in JUDGES],
        "n_chains": len(baselines),
        "n_variants": len(VARIANTS_SPEC),
        "useful_threshold": USEFUL_THRESHOLD,
        "python_version": sys.version,
        "scipy_version": __import__("scipy").__version__,
        "numpy_version": np.__version__,
    }
    (RESULTS / "run_metadata.json").write_text(json.dumps(meta, indent=2))
    (RESULTS / "run.log").write_text("\n".join(LOG_LINES) + "\n")
    log("done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
