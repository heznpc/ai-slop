#!/usr/bin/env python3
"""
H-Text: Adversarial Text Detection — Runner
============================================

Pre-registered protocol: ./protocol.md (locked 2026-05-21)

Reuses baselines from experiments/h_spill/ (stage 1 news articles + cached
2-judge ai_probability). Generates 2 adversarial variants per baseline,
judges them, then runs paired Wilcoxon + threshold test.

Pipeline:
  1. load_baselines()        -> first 15 chains from H-Spill stage 1
  2. generate_variants()     Sonnet 4.6 -> results/variants/<id>_<A|B>.txt (30 calls)
  3. judge_variants()        Opus 4.7 + Gemini 2.5 Flash, concurrent (60 calls)
  4. analyze()               threshold + Wilcoxon -> results/h_text_stats.json
"""

from __future__ import annotations

