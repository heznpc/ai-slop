#!/bin/bash
# Shell-loop judging for H-Text variants. Mirrors experiments/h_spill/shell_judge.sh.

cd "$(dirname "$0")"
RESULTS=results
VARIANTS=$RESULTS/variants
JUDGMENTS=$RESULTS/judgments
JUDGE_ID=gemini25flash
MODEL=gemini-2.5-flash
PROMPT_PREFIX='You are evaluating whether a piece of text was generated by an AI (LLM) or written by a human. Return only a JSON object with exactly two fields: ai_probability (float between 0.0 and 1.0; 1.0 = definitely AI, 0.0 = definitely human, 0.5 = uncertain) and reasoning (1-2 sentence justification). Reply with the JSON object only, no other text.

TEXT TO EVALUATE:

'

n_done=0
n_skip=0
for vfile in "$VARIANTS"/*.txt; do
  [ -f "$vfile" ] || continue
  basename=$(basename "$vfile" .txt)  # e.g., W7107944698_A
  json_file="$JUDGMENTS/${basename}_${JUDGE_ID}.json"
  meta_file="$JUDGMENTS/${basename}_${JUDGE_ID}.meta.json"
  if [ -f "$json_file" ]; then
    n_skip=$((n_skip+1))
    continue
  fi
  text=$(cat "$vfile")
  echo "[$(date +%H:%M:%S)] judging $basename/$JUDGE_ID..."
  t0=$(date +%s)
  envelope=$(gemini -m "$MODEL" -o json -p "$PROMPT_PREFIX$text" 2>/dev/null)
  t1=$(date +%s)
  wall=$((t1 - t0))
  parsed=$(echo "$envelope" | python3 -c "
import json, sys, re
t = sys.stdin.read()
try:
    env = json.loads(t)
    resp = env.get('response', '')
    resp = re.sub(r'^\`\`\`(?:json)?\s*', '', resp.strip(), flags=re.MULTILINE)
    resp = re.sub(r'\`\`\`\s*\$', '', resp.strip(), flags=re.MULTILINE)
    m = re.search(r'\{[^{}]*\"ai_probability\"[^{}]*\}', resp, re.DOTALL)
    if m:
        d = json.loads(m.group(0))
        if 'ai_probability' in d and 0 <= float(d['ai_probability']) <= 1:
            print(json.dumps({'ai_probability': float(d['ai_probability']), 'reasoning': d.get('reasoning','')}, indent=2))
            sys.exit(0)
except Exception:
    pass
sys.exit(1)
" 2>/dev/null)
  if [ -n "$parsed" ]; then
    echo "$parsed" > "$json_file"
    echo "$envelope" | python3 -c "
import json, sys
d = json.loads(sys.stdin.read())
sm = (d.get('stats') or {}).get('models') or {}
out = {'basename': '$basename', 'judge': '$JUDGE_ID', 'wall_s': $wall}
if sm:
    k = next(iter(sm))
    m = sm[k]
    tk = m.get('tokens') or {}
    api = m.get('api') or {}
    out['input_tokens'] = tk.get('input')
    out['output_tokens'] = tk.get('candidates')
    out['duration_ms'] = api.get('totalLatencyMs')
print(json.dumps(out, indent=2))
" > "$meta_file"
    n_done=$((n_done+1))
    ai_p=$(python3 -c "import json; print(json.load(open('$json_file'))['ai_probability'])")
    echo "  -> ai_p=$ai_p (${wall}s)  done_this_run=$n_done"
  else
    echo "  -> PARSE-FAIL (${wall}s)"
  fi
done
echo "=== shell_judge done: n_done=$n_done n_skip=$n_skip ==="
